using System;
using System.Collections.Generic;

namespace Sharp.OpenIddict.Stores.ServerAcceptance;

/// <summary>
/// Names and recognises the table prefixes the acceptance fixtures create on servers that give the run no
/// database of its own (PostgreSQL, Oracle, and DM install into a schema other things may share). The run's
/// identity is a short valid-identifier prefix carrying a GUID fragment, and cleanup may only ever touch the
/// nine exact table names this run's prefix produces — a pre-existing deployment under the default prefix,
/// and everything else in the schema, is untouchable by construction.
/// </summary>
internal static class TestTablePrefix
{
    /// <summary>The stem every generated prefix carries; the ownership check keys off it.</summary>
    public const string Stem = "Oit";

    /// <summary>
    /// A prefix unique to this test run. It is a valid identifier everywhere (letters and digits, not
    /// starting with a digit), short enough for the longest rendered name to stay under the 63-byte
    /// PostgreSQL limit, and distinct from the default "OpenIddict" so a shared schema that already hosts a
    /// real deployment is never touched.
    /// </summary>
    public static string Create()
        => Stem + Guid.NewGuid().ToString("N").Substring(0, 12);

    /// <summary>
    /// Whether <paramref name="prefix"/> was generated by <see cref="Create"/>. Used as a guard immediately
    /// before destructive cleanup: a hand-written "Oit..." prefix without the GUID fragment is not ours and
    /// must be left alone.
    /// </summary>
    public static bool IsOwnedByThisTestRun(string? prefix)
    {
        if (string.IsNullOrEmpty(prefix) || !prefix!.StartsWith(Stem, StringComparison.Ordinal))
        {
            return false;
        }

        var fragment = prefix[Stem.Length..];

        return fragment.Length == 12 && Guid.TryParseExact("00000000-0000-0000-0000-" + fragment, "D", out _);
    }

    /// <summary>The nine table names this prefix produces, in the exact form the templates create them.</summary>
    public static IReadOnlyList<string> OwnedTableNames(string prefix) => new[]
    {
        prefix + "Applications",
        prefix + "ApplicationRedirectUris",
        prefix + "ApplicationPostLogoutRedirectUris",
        prefix + "Authorizations",
        prefix + "AuthorizationScopes",
        prefix + "Scopes",
        prefix + "ScopeResources",
        prefix + "Tokens",
        prefix + "SchemaVersions",
    };

    /// <summary>
    /// The owned tables in a foreign-key-safe drop order: children before the rows they reference. Indexes
    /// and constraints disappear with their tables, so names alone are enough.
    /// </summary>
    public static IReadOnlyList<string> DropOrder { get; } = new[]
    {
        "Tokens",
        "AuthorizationScopes",
        "ScopeResources",
        "ApplicationRedirectUris",
        "ApplicationPostLogoutRedirectUris",
        "Authorizations",
        "Scopes",
        "Applications",
        "SchemaVersions",
    };
}
