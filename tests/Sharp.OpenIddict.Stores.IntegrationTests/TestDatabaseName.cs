using System;

namespace Sharp.OpenIddict.Stores.IntegrationTests;

/// <summary>
/// Names and recognises the databases and files created by the test run (ENG-05).
/// </summary>
/// <remarks>
/// A test suite that talks to a real server must be unable to delete anything it did not create. Relying on
/// "the name looks generated" is not enough once a fixture is pointed at a shared server: one bad variable, one
/// stale field, and the cleanup path drops a database that belongs to someone else. Naming and recognising the
/// run's own resources is therefore centralised here, so every fixture applies the same rule and a test can
/// prove the rule holds.
/// </remarks>
internal static class TestDatabaseName
{
    /// <summary>The prefix every generated name carries; the ownership check keys off it.</summary>
    public const string Prefix = "oidc-test-";

    /// <summary>A name unique to this test run, so parallel fixtures never collide on a shared server.</summary>
    public static string Create(string purpose)
        => $"{Prefix}{purpose}-{Guid.NewGuid():N}";

    /// <summary>
    /// Whether <paramref name="name"/> was generated by <see cref="Create"/>. Used as a guard immediately
    /// before destructive cleanup: anything else must be left alone.
    /// </summary>
    public static bool IsOwnedByThisTestRun(string? name)
    {
        if (string.IsNullOrEmpty(name) || !name!.StartsWith(Prefix, StringComparison.Ordinal))
        {
            return false;
        }

        // The suffix must be a GUID in "N" format, so a name that merely starts with the prefix - a user's
        // database called "oidc-test-manual", for example - is still rejected.
        var suffix = name[Prefix.Length..];
        var separator = suffix.LastIndexOf('-');

        return separator >= 0
            && suffix.Length - separator - 1 == 32
            && Guid.TryParseExact(suffix[(separator + 1)..], "N", out _);
    }

    /// <summary>The temporary file path used by the file-database fixtures.</summary>
    public static string CreateFilePath(string purpose)
        => System.IO.Path.Combine(System.IO.Path.GetTempPath(), Create(purpose) + ".db");

    /// <summary>Whether a temporary database file belongs to this test run.</summary>
    public static bool IsOwnedDatabaseFile(string? path)
        => !string.IsNullOrEmpty(path)
            && IsOwnedByThisTestRun(System.IO.Path.GetFileNameWithoutExtension(path));
}
